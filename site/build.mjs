// Builds the static site into _site/.
//
// - Every *.md file in the repository becomes a page with the same path and
//   an .html extension. A directory's README.md becomes its index.html when
//   the directory has no index.md (the way GitHub Pages used to do it).
// - Every other file (ttl, rq, images, ...) is copied as it is.
// - assets/css/style.scss is compiled to assets/css/style.css.
// - Lines holding {{resource-grid}}, {{resource-legend}} and
//   {{deprecated-section}} on the home page are filled from data/*.yml.
// - _site/search-index.json is written from the lists on the examples' index
//   pages, for the search box in the header.
//
// The examples' own Markdown (index.md, <query>.md) and the .rq/.ttl files are
// generated by sparql-examples-utils in CI, see .github/workflows.
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import MarkdownIt from 'markdown-it';
import yaml from 'js-yaml';
import * as sass from 'sass';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, '_site');
const TEMPLATES = path.join(ROOT, 'site', 'templates');

const SITE = {
  title: 'SIB SPARQL examples',
  description: 'A collection of SPARQL examples for SIB Swiss Institute of Bioinformatics resources',
  repositoryUrl: 'https://github.com/sib-swiss/sparql-examples',
  repositoryName: 'sib-swiss/sparql-examples',
};

// Never published: build inputs, dependencies, tooling and developer notes.
// Top-level only, so a directory named like one of these deeper down is fine.
// Like Jekyll did, anything at the top level whose name starts with "_" is skipped too.
const SKIPPED_TOP_DIRECTORIES = new Set(['node_modules', 'site', 'data', '_site']);
const SKIPPED_TOP_FILES = new Set(['README.md', 'package.json', 'package-lock.json', 'Dockerfile', 'Gemfile', 'Gemfile.lock']);

const md = new MarkdownIt({ html: true, linkify: true });

// [x](./foo.md) links point at the built page, foo.html. Absolute URLs and
// in-page anchors are left alone.
const defaultLinkOpen = md.renderer.rules.link_open;
md.renderer.rules.link_open = (tokens, idx, options, env, self) => {
  const token = tokens[idx];
  const href = token.attrGet('href');
  if (href && !/^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(href)) {
    token.attrSet('href', href.replace(/\.md(?=$|#)/, '.html'));
  }
  return defaultLinkOpen
    ? defaultLinkOpen(tokens, idx, options, env, self)
    : self.renderToken(tokens, idx, options);
};

// Headings get GitHub-style ids (## Examples -> id="examples"), which the
// examples table script looks for. Jekyll added these, markdown-it does not.
md.core.ruler.push('heading_ids', (state) => {
  const seen = new Map();
  const tokens = state.tokens;
  for (let i = 0; i < tokens.length - 1; i++) {
    if (tokens[i].type !== 'heading_open') continue;
    const text = tokens[i + 1].children
      .filter((t) => t.type === 'text' || t.type === 'code_inline')
      .map((t) => t.content)
      .join('');
    let slug = text.toLowerCase().replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');
    const count = seen.get(slug) ?? 0;
    seen.set(slug, count + 1);
    if (count > 0) slug = `${slug}-${count}`;
    tokens[i].attrSet('id', slug);
  }
});

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function readYaml(name) {
  return yaml.load(readFileSync(path.join(ROOT, 'data', name), 'utf8'));
}

const RESOURCES = readYaml('resources.yml');
const CATEGORIES = readYaml('categories.yml');

// Every file in the repository that gets published, as posix paths relative to ROOT.
function listFiles(relDir = '') {
  const files = [];
  const entries = readdirSync(path.join(ROOT, relDir), { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const rel = relDir ? `${relDir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!relDir && (SKIPPED_TOP_DIRECTORIES.has(entry.name) || entry.name.startsWith('_'))) continue;
      files.push(...listFiles(rel));
    } else if (entry.isFile()) {
      if (!relDir && (SKIPPED_TOP_FILES.has(entry.name) || entry.name.startsWith('_'))) continue;
      files.push(rel);
    }
  }
  return files;
}

function stripFrontMatter(source) {
  return source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '');
}

function firstHeading(body) {
  const match = body.match(/^#\s+(.+?)\s*#*\s*$/m);
  return match ? match[1] : null;
}

// The home page's resource lists, generated from data/resources.yml.
function homePageBlocks() {
  const resources = RESOURCES;
  const categories = CATEGORIES;
  const active = resources.filter((r) => r.category !== 'deprecated');
  const deprecated = resources.filter((r) => r.category === 'deprecated');

  const grid = (list, extraClass = '') =>
    `<ul class="resource-grid${extraClass}">\n` +
    list
      .map((r) => `  <li class="category-${r.category}"><a href="./examples/${r.path}/">${escapeHtml(r.name)}</a></li>`)
      .join('\n') +
    '\n</ul>';

  const usedCategories = [...new Set(active.map((r) => r.category))];
  const legend =
    '<ul class="resource-grid-legend">\n' +
    usedCategories
      .map((slug) => `  <li class="resource-grid-legend__item category-${slug}">${escapeHtml(categories[slug].label)}</li>`)
      .join('\n') +
    '\n</ul>';

  const deprecatedSection = deprecated.length
    ? '## Deprecated resources\n\n' +
      'These SPARQL endpoints are no longer actively maintained; their examples are kept here for reference.\n\n' +
      grid(deprecated, ' resource-grid--deprecated')
    : '';

  return {
    'resource-grid': grid(active),
    'resource-legend': legend,
    'deprecated-section': deprecatedSection,
  };
}

function fillHomePage(source) {
  const blocks = homePageBlocks();
  return source.replace(/^\{\{([a-z-]+)\}\}$/gm, (token, name) => (name in blocks ? blocks[name] : token));
}

// The search index: one entry per item of an examples/<resource>/index.md list,
// lines like ` - [Label@en](./query.md)`.
function searchIndex(sources) {
  const entries = [];
  for (const [rel, source] of sources) {
    const match = rel.match(/^examples\/([^/]+)\/index\.md$/);
    if (!match) continue;
    const resource = match[1];
    const entry = RESOURCES.find((r) => r.path === resource);
    const deprecated = Boolean(entry && entry.category === 'deprecated');
    for (const line of source.split('\n')) {
      const item = line.match(/ - \[([^\]]*)\]\(([^)]*)\)/);
      if (!item) continue;
      const title = item[1].replaceAll('@en', '').trim();
      const link = item[2].trim();
      const url = link.startsWith('/')
        ? link
        : `/examples/${resource}/${link.replaceAll('./', '').replaceAll('.md', '.html')}`;
      entries.push({ title, url, resource, deprecated });
    }
  }
  return entries;
}

function renderLayout(template, values) {
  // Single pass: values inserted here are never scanned for placeholders.
  return template.replace(/\{\{(\w+)\}\}/g, (token, key) => (key in values ? values[key] : token));
}

function loadLayout() {
  return readFileSync(path.join(TEMPLATES, 'layout.html'), 'utf8').replace(
    /<!-- include: ([\w.-]+) -->/g,
    (_, file) => readFileSync(path.join(TEMPLATES, file), 'utf8'),
  );
}

function main() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });

  const files = listFiles();
  const markdownFiles = files.filter((f) => f.endsWith('.md'));
  const markdownSet = new Set(markdownFiles);

  const sources = new Map();
  for (const rel of markdownFiles) {
    sources.set(rel, readFileSync(path.join(ROOT, rel), 'utf8'));
  }

  const layout = loadLayout();
  const pages = [];

  for (const rel of markdownFiles) {
    const dir = path.posix.dirname(rel);
    const base = path.posix.basename(rel);
    const outName =
      base === 'README.md' && !markdownSet.has(`${dir}/index.md`) ? 'index.md' : base;
    const outPath = (dir === '.' ? '' : `${dir}/`) + outName.replace(/\.md$/, '.html');
    const isHome = outPath === 'index.html';

    let body = stripFrontMatter(sources.get(rel));
    if (isHome) body = fillHomePage(body);

    const heading = firstHeading(body);
    const title = isHome ? SITE.title : heading ? `${heading} | ${SITE.title}` : SITE.title;

    const resourceMatch = outPath.match(/(?:^|\/)examples\/([^/]+)\/index\.html$/);
    const resource = resourceMatch ? RESOURCES.find((r) => r.path === resourceMatch[1]) : null;
    const badge = resource
      ? `<p class="category-badge category-${resource.category}">${escapeHtml(CATEGORIES[resource.category].label)}</p>`
      : '';

    const html = renderLayout(layout, {
      title: escapeHtml(title),
      description: escapeHtml(SITE.description),
      siteTitle: escapeHtml(SITE.title),
      repositoryUrl: SITE.repositoryUrl,
      repositoryName: SITE.repositoryName,
      breadcrumb: isHome ? '' : '<p class="breadcrumb"><a href="/">&larr; All examples</a></p>',
      badge,
      content: md.render(body),
    });

    const outFile = path.join(OUT, outPath);
    mkdirSync(path.dirname(outFile), { recursive: true });
    writeFileSync(outFile, html);
    pages.push(outPath);
  }

  for (const rel of files) {
    if (rel.endsWith('.md') || rel.endsWith('.scss')) continue;
    const outFile = path.join(OUT, rel);
    mkdirSync(path.dirname(outFile), { recursive: true });
    cpSync(path.join(ROOT, rel), outFile);
  }

  const css = sass.compile(path.join(ROOT, 'assets', 'css', 'style.scss'), { style: 'compressed' }).css;
  mkdirSync(path.join(OUT, 'assets', 'css'), { recursive: true });
  writeFileSync(path.join(OUT, 'assets', 'css', 'style.css'), css);

  writeFileSync(path.join(OUT, 'search-index.json'), JSON.stringify(searchIndex(sources)));

  console.log(`Built ${pages.length} pages into ${path.relative(ROOT, OUT)}/`);
}

main();
